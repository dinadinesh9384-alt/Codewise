"""Opt-in integration tests against a dedicated PostgreSQL test database.

Set CODEWISE_TEST_POSTGRESQL_URL to a disposable database whose name contains
"test". These tests create LangGraph checkpoint tables in that database.
"""

import importlib.util
import os
import uuid
import unittest
from typing import TypedDict
from urllib.parse import urlparse


_DATABASE_URL = os.environ.get("CODEWISE_TEST_POSTGRESQL_URL", "")
_HAS_DEPENDENCIES = all(importlib.util.find_spec(name) for name in
                        ("psycopg", "psycopg_pool", "langgraph.checkpoint.postgres"))
_SKIP_REASON = ("PostgreSQL integration tests require CODEWISE_TEST_POSTGRESQL_URL pointing to an "
                "explicitly disposable database whose name contains 'test', plus the declared "
                "psycopg, psycopg_pool, and langgraph-checkpoint-postgres dependencies.")


class _CheckpointState(TypedDict, total=False):
    execution_id: str
    snapshot_id: str
    decision: str


@unittest.skipUnless(_DATABASE_URL and _HAS_DEPENDENCIES, _SKIP_REASON)
class PostgreSQLCheckpointIntegrationTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        parsed = urlparse(_DATABASE_URL)
        if parsed.scheme not in {"postgres", "postgresql"} or not parsed.path or "test" not in parsed.path.lower():
            raise unittest.SkipTest("CODEWISE_TEST_POSTGRESQL_URL must be a PostgreSQL URL for a disposable "
                                    "database whose name contains 'test'.")
        from langgraph.checkpoint.postgres import PostgresSaver
        from langgraph.checkpoint.serde.jsonplus import JsonPlusSerializer
        from psycopg.rows import dict_row
        from psycopg_pool import ConnectionPool

        cls.pool = ConnectionPool(conninfo=_DATABASE_URL,
            kwargs={"autocommit": True, "row_factory": dict_row}, min_size=1, max_size=4)
        cls.pool.wait(timeout=5)
        cls.saver = PostgresSaver(cls.pool, serde=JsonPlusSerializer(allowed_msgpack_modules=[]))
        cls.saver.setup()
        cls.thread_ids = set()

    def _config(self, execution_id):
        self.thread_ids.add(str(execution_id))
        return {"configurable": {"thread_id": str(execution_id)}}

    @classmethod
    def tearDownClass(cls):
        if hasattr(cls, "pool"):
            # Thread IDs are generated by these tests and are safe to remove.
            # Keep the schema/migration records intact for other tests in this
            # explicitly disposable database.
            for thread_id in getattr(cls, "thread_ids", ()):
                with cls.pool.connection() as connection:
                    for table in ("checkpoint_writes", "checkpoint_blobs", "checkpoints"):
                        connection.execute(f"DELETE FROM {table} WHERE thread_id = %s", (thread_id,))
            cls.pool.close()

    @staticmethod
    def _graph(saver):
        from langgraph.graph import END, START, StateGraph
        from langgraph.types import interrupt

        graph = StateGraph(_CheckpointState)

        def approval_gate(state):
            decision = interrupt({"execution_id": state["execution_id"],
                                  "snapshot_id": state["snapshot_id"]})
            return {"decision": decision}

        graph.add_node("approval_gate", approval_gate)
        graph.add_edge(START, "approval_gate")
        graph.add_edge("approval_gate", END)
        return graph.compile(checkpointer=saver)

    def test_setup_created_required_checkpoint_tables_and_they_are_accessible(self):
        with self.pool.connection() as connection:
            for table in ("checkpoint_migrations", "checkpoints", "checkpoint_blobs", "checkpoint_writes"):
                connection.execute(f"SELECT 1 FROM {table} LIMIT 0")

    def test_approval_interrupt_persists_across_saver_reconstruction_and_resumes(self):
        from langgraph.types import Command

        execution_id, snapshot_id = str(uuid.uuid4()), str(uuid.uuid4())
        config = self._config(execution_id)
        graph = self._graph(self.saver)
        paused = graph.invoke({"execution_id": execution_id, "snapshot_id": snapshot_id}, config)
        self.assertTrue(paused.get("__interrupt__"))
        with ConnectionPoolProxy(_DATABASE_URL) as (pool, saver):
            restarted_graph = self._graph(saver)
            current = restarted_graph.get_state(config)
            self.assertEqual(current.values["execution_id"], execution_id)
            self.assertEqual(current.values["snapshot_id"], snapshot_id)
            resumed = restarted_graph.invoke(Command(resume="approved"), config)
            self.assertEqual(resumed["decision"], "approved")

    def test_checkpoint_threads_are_isolated_by_execution_uuid(self):
        first_id, second_id = str(uuid.uuid4()), str(uuid.uuid4())
        graph = self._graph(self.saver)
        first_config = self._config(first_id)
        second_config = self._config(second_id)
        graph.invoke({"execution_id": first_id, "snapshot_id": "snapshot-one"}, first_config)
        graph.invoke({"execution_id": second_id, "snapshot_id": "snapshot-two"}, second_config)
        self.assertEqual(graph.get_state(first_config).values["snapshot_id"], "snapshot-one")
        self.assertEqual(graph.get_state(second_config).values["snapshot_id"], "snapshot-two")

    def test_execution_uuid_mismatch_cannot_resume_another_execution_thread(self):
        from langgraph.types import Command

        execution_id, foreign_execution_id = str(uuid.uuid4()), str(uuid.uuid4())
        graph = self._graph(self.saver)
        owner_config = self._config(execution_id)
        foreign_config = self._config(foreign_execution_id)
        graph.invoke({"execution_id": execution_id, "snapshot_id": "snapshot-owner"}, owner_config)

        self.assertIsNone(graph.get_state(foreign_config).values.get("execution_id"))
        foreign_resume = graph.invoke(Command(resume="approved"), foreign_config)
        self.assertFalse(foreign_resume.get("decision"))
        self.assertTrue(graph.get_state(owner_config).tasks[0].interrupts)

    def test_snapshot_identity_is_bound_to_the_persisted_execution_checkpoint(self):
        execution_id = str(uuid.uuid4())
        config = self._config(execution_id)
        graph = self._graph(self.saver)
        paused = graph.invoke({"execution_id": execution_id, "snapshot_id": "snapshot-original"}, config)
        graph.invoke({"execution_id": execution_id, "snapshot_id": "snapshot-substituted"}, config)

        current = graph.get_state(config)
        self.assertEqual(current.values["snapshot_id"], "snapshot-original")
        self.assertEqual(paused["__interrupt__"][0].value["snapshot_id"], "snapshot-original")

    def test_checkpoint_advance_survives_failure_in_a_separate_decision_transaction(self):
        """A PostgreSQL checkpoint commit is not rolled back with a second transaction."""
        from langgraph.types import Command

        execution_id, snapshot_id = str(uuid.uuid4()), str(uuid.uuid4())
        config = self._config(execution_id)
        graph = self._graph(self.saver)
        graph.invoke({"execution_id": execution_id, "snapshot_id": snapshot_id}, config)

        # Model the service ordering: LangGraph commits through its pool, then
        # decision persistence fails and its independent transaction rolls back.
        try:
            with self.pool.connection() as connection:
                with connection.transaction():
                    resumed = graph.invoke(Command(resume="approved"), config)
                    self.assertEqual(resumed["decision"], "approved")
                    raise RuntimeError("injected decision persistence failure")
        except RuntimeError as exc:
            self.assertEqual(str(exc), "injected decision persistence failure")

        with ConnectionPoolProxy(_DATABASE_URL) as (_, reconstructed_saver):
            recovered_graph = self._graph(reconstructed_saver)
            recovered = recovered_graph.get_state(config)
            self.assertEqual(recovered.values.get("decision"), "approved")
            self.assertEqual(recovered.values["execution_id"], execution_id)


class ConnectionPoolProxy:
    """Short-lived independent pool/saver representing a reconstructed runtime."""

    def __init__(self, dsn):
        self.dsn = dsn

    def __enter__(self):
        from langgraph.checkpoint.postgres import PostgresSaver
        from langgraph.checkpoint.serde.jsonplus import JsonPlusSerializer
        from psycopg.rows import dict_row
        from psycopg_pool import ConnectionPool

        self.pool = ConnectionPool(conninfo=self.dsn,
            kwargs={"autocommit": True, "row_factory": dict_row}, min_size=1, max_size=2)
        self.pool.wait(timeout=5)
        self.saver = PostgresSaver(self.pool, serde=JsonPlusSerializer(allowed_msgpack_modules=[]))
        return self.pool, self.saver

    def __exit__(self, *exc_info):
        self.pool.close()
